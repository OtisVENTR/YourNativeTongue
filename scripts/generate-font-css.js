#!/usr/bin/env node

/**
 * Font CSS Generator
 * Scans assets/fonts directory and generates optimized @font-face declarations
 *
 * Usage: node scripts/generate-font-css.js
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const FONTS_DIR = path.join(__dirname, '../src/assets/fonts');
const OUTPUT_FILE = path.join(__dirname, '../src/styles/fonts.css');

// Font weight mapping
const WEIGHT_MAP = {
  thin: 100,
  extralight: 200,
  light: 300,
  regular: 400,
  normal: 400,
  medium: 500,
  semibold: 600,
  bold: 700,
  extrabold: 800,
  black: 900,
};

// Format priority (best to worst)
const FORMAT_PRIORITY = ['woff2', 'woff', 'ttf', 'otf'];

function parseFontFile(filename) {
  const name = path.basename(filename, path.extname(filename));
  const ext = path.extname(filename).slice(1).toLowerCase();
  
  // Extract font name and weight
  const parts = name.split('-');
  const fontName = parts[0];
  const weightPart = parts.find(p => 
    Object.keys(WEIGHT_MAP).includes(p.toLowerCase()) || 
    /^\d+$/.test(p)
  );
  
  const isItalic = name.toLowerCase().includes('italic') || 
                   name.toLowerCase().includes('oblique');
  
  let weight = 400; // default
  if (weightPart) {
    const weightLower = weightPart.toLowerCase();
    weight = WEIGHT_MAP[weightLower] || parseInt(weightPart) || 400;
  }
  
  return {
    fontName,
    weight,
    style: isItalic ? 'italic' : 'normal',
    format: ext,
    filename,
  };
}

function groupFonts(files) {
  const groups = {};
  
  files.forEach(file => {
    const key = `${file.fontName}-${file.weight}-${file.style}`;
    if (!groups[key]) {
      groups[key] = {
        fontName: file.fontName,
        weight: file.weight,
        style: file.style,
        formats: [],
      };
    }
    
    groups[key].formats.push({
      format: file.format,
      filename: file.filename,
    });
  });
  
  // Sort formats by priority
  Object.values(groups).forEach(group => {
    group.formats.sort((a, b) => {
      const aIndex = FORMAT_PRIORITY.indexOf(a.format);
      const bIndex = FORMAT_PRIORITY.indexOf(b.format);
      return (aIndex === -1 ? 999 : aIndex) - (bIndex === -1 ? 999 : bIndex);
    });
  });
  
  return groups;
}

function generateFontFace(group) {
  const { fontName, weight, style, formats } = group;

  const srcParts = formats.map(f => {
    const formatMap = {
      woff2: 'woff2',
      woff: 'woff',
      ttf: 'truetype',
      otf: 'opentype',
      eot: 'embedded-opentype',
    };

    const format = formatMap[f.format] || f.format;
    return `url('../assets/fonts/${f.filename}') format('${format}')`;
  });
  
  return `@font-face {
  font-family: '${fontName}';
  src: ${srcParts.join(',\n       ')};
  font-weight: ${weight};
  font-style: ${style};
  font-display: swap;
  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
}`;
}

function generateCSS() {
  if (!fs.existsSync(FONTS_DIR)) {
    console.log(`Fonts directory not found: ${FONTS_DIR}`);
    console.log('Creating directory...');
    fs.mkdirSync(FONTS_DIR, { recursive: true });
    return;
  }
  
  const files = fs.readdirSync(FONTS_DIR)
    .filter(f => /\.(woff2?|ttf|otf|eot)$/i.test(f))
    .map(f => parseFontFile(f));
  
  if (files.length === 0) {
    console.log('No font files found in assets/fonts/');
    console.log('Please add your font files and run this script again.');
    return;
  }
  
  const groups = groupFonts(files);
  const fontFaces = Object.values(groups).map(generateFontFace);
  
  const css = `/**
 * Custom Font Declarations
 * Auto-generated by scripts/generate-font-css.js
 * Last updated: ${new Date().toISOString()}
 * 
 * Optimized with font-display: swap for better performance
 * Supports WOFF2 (preferred), WOFF, TTF, and OTF formats
 */

${fontFaces.join('\n\n')}
`;
  
  fs.writeFileSync(OUTPUT_FILE, css, 'utf8');
  console.log(`✅ Generated font CSS with ${fontFaces.length} @font-face declarations`);
  console.log(`   Output: ${OUTPUT_FILE}`);
}

// Run if called directly
generateCSS();

export { generateCSS };

